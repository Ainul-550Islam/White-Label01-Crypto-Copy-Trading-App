/**
 * Part 9 safety tests for the operations surface.
 *
 * Four families, in the order their failures would hurt:
 *
 *  1. CROSS-LANGUAGE PARITY against the Python engine. The TS registry,
 *     evaluator, alert catalog and redaction predicate are hand-written
 *     mirrors of `wlct_trading.observability`. Drift is silent and lands on
 *     an operator's screen during an incident, so BOTH the shared fixture
 *     (generated by libs/trading-core/scripts/gen_observability_fixtures.py)
 *     and live parses of the Python sources are asserted here. A constant
 *     edited on one side fails this suite in CI.
 *
 *  2. METRIC CARDINALITY GUARANTEES. No order ids, no request ids, no
 *     tenant/user identifiers, no URL- or credential-shaped values, allow-
 *     listed label names, bounded symbol domains, and a series cap that
 *     refuses NEW series instead of growing forever. These are the rules
 *     that keep the metrics backend alive; they are asserted against the
 *     rendered text and against the source of every metric-registering file.
 *
 *  3. WHAT THE OPERATIONS SURFACE CANNOT DO. No route disables the risk
 *     engine, submits an order, or touches a kill switch; every mutation is
 *     a POST with a DTO, a permission and an audit path; readiness reports
 *     and nothing in the trading path imports the readiness evaluator.
 *
 *  4. THE READINESS TRUTH TABLE. All 512 gate combinations replayed against
 *     the fixture computed by the Python evaluator, plus the unknown- and
 *     stale-evidence tables. "Both panels agree" is only meaningful if some-
 *     thing checks it mechanically at every commit.
 */

