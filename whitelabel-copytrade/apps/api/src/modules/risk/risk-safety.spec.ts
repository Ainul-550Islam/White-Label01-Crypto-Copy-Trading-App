/**
 * Part 8 safety tests for the risk control plane.
 *
 * Three families of assertions, in order of how much they are worth:
 *
 *  1. CROSS-LANGUAGE PARITY. The TypeScript constants and canonicalisation
 *     are hand-written replicas of Python truth (`wlct_trading.enums`,
 *     `wlct_trading.risk.configuration`). Two hand-written copies of one
 *     rule drift, and the drift is silent: the API would happily publish a
 *     configuration whose digest the engine computes differently, and every
 *     snapshot would refuse to bind. The fixtures under docs/fixtures are
 *     GENERATED by `libs/trading-core/scripts/gen_risk_digest_fixtures.py`,
 *     and the Python source is additionally parsed live so a constant edit
 *     on one side fails this suite in CI, not in production.
 *
 *  2. WHAT THIS SURFACE CANNOT DO, asserted by reading the shipped source:
 *     no PUT/PATCH/DELETE routes, no order execution or approval anywhere in
 *     the module, no writes to order tables, no execution-queue traffic, and
 *     the two typed-confirmation phrases are different strings that each
 *     appear exactly where they must.
 *
 *  3. THE ENVIRONMENT GATE. `RISK_FAIL_CLOSED=false` has no legal value
 *     anywhere - not in test, not in production - and the window orderings
 *     that would make a ceiling unreachable are refused at boot.
 *
 * No database, no network, no venue, no secrets.
 */

function baseEnv(overrides: Record<string, string> = {}): Record<string, string> {
  return {
    NODE_ENV: 'test',
    DATABASE_URL: 'postgresql://user:pass@localhost:5432/db?schema=public',
    DIRECT_DATABASE_URL: 'postgresql://user:pass@localhost:5432/db?schema=public',
    REDIS_URL: 'redis://localhost:6379/0',
    JWT_ACCESS_SECRET: 'a'.repeat(48),
    JWT_REFRESH_SECRET: 'b'.repeat(48),
    ENCRYPTION_MASTER_KEY_BASE64: Buffer.alloc(32, 7).toString('base64'),
    BLIND_INDEX_KEY_BASE64: Buffer.alloc(32, 9).toString('base64'),
    INTERNAL_SERVICE_TOKEN: 'c'.repeat(32),
    EXCHANGE_WEBHOOK_SIGNING_SECRET: 'd'.repeat(32),
    ...overrides,
  };
}

function failurePaths(env: Record<string, string>): string[] {
  try {
    validateEnv(env);
  } catch (error) {
    if (error instanceof EnvValidationError) {
      return error.failures.map((entry) => entry.path);
    }
    throw error;
  }
  throw new Error('Expected validation to fail, but it succeeded.');
}

