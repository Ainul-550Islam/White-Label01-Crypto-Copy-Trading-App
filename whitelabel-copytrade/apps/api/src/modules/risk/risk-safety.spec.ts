const pythonEnumsSource = readFileSync(join(TRADING_CORE_SRC, 'enums.py'), 'utf-8');

function parseRuleOrder(): string[] {
  const block = /RISK_RULE_ORDER: tuple\[RiskRuleId, \.\.\.\] = \(([\s\S]*?)\n\)/u.exec(
    pythonEnumsSource,
  );
  if (!block) {
    throw new Error('Could not locate RISK_RULE_ORDER in enums.py - did the shape change?');
  }
  return [...block[1].matchAll(/RiskRuleId\.([A-Z_]+)/gu)].map((match) => match[1]);
}

function parseRuleUnits(): Record<string, string[]> {
  const start = pythonEnumsSource.indexOf('RISK_RULE_UNITS: dict');
  const end = pythonEnumsSource.indexOf('\n}', start);
  if (start < 0 || end < 0) {
    throw new Error('Could not locate RISK_RULE_UNITS in enums.py');
  }
  const block = pythonEnumsSource.slice(start, end);
  const out: Record<string, string[]> = {};
  for (const match of block.matchAll(
    /RiskRuleId\.([A-Z_]+):\s*frozenset\(\s*\{([^}]*)\}\s*\)/gu,
  )) {
    const units = [...match[2].matchAll(/RiskLimitUnit\.([A-Z_]+)/gu)].map((u) => u[1]);
    out[match[1]] = [...units].sort();
  }
  return out;
}

function parseSwitchTransitions(): Record<string, string[]> {
  const start = pythonEnumsSource.indexOf('RISK_SWITCH_TRANSITIONS: dict');
  const end = pythonEnumsSource.indexOf('\n}', start);
  if (start < 0 || end < 0) {
    throw new Error('Could not locate RISK_SWITCH_TRANSITIONS in enums.py');
  }
  const block = pythonEnumsSource.slice(start, end);
  const out: Record<string, string[]> = {};
  for (const match of block.matchAll(
    /RiskSwitchStatus\.([A-Z_]+):\s*frozenset\(\s*\{([^}]*)\}\s*\)/gu,
  )) {
    const targets = [...match[2].matchAll(/RiskSwitchStatus\.([A-Z_]+)/gu)].map((t) => t[1]);
    out[match[1]] = [...targets].sort();
  }
  return out;
}

