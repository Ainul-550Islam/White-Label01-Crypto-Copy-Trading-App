#!/usr/bin/env bash
# # Removes the two files Batch 04 deletes, idempotently and without failing on a second run.
#
# 1. apps/admin-web/src/middleware.ts
#    Next 16 accepts ONE request entrypoint per application and calls it the
#    proxy. Having both entrypoints made `npm run check:next-entrypoints` fail
#    and `next build` refuse the app outright ("both middleware and proxy files
#    detected"). Every behaviour of the deleted module - the public-path
#    allowlist, the login redirect with its `next` destination, the `/api/*`
#    exemption, the per-request CSP nonce, the exact CSP directive list, the
#    static security headers and the matcher - now lives in src/proxy.ts and is
#    proven behaviour by behaviour in src/tests/entrypoint-proxy.test.ts.
#
# 2. apps/web/next-env.d.ts
#    This file is GENERATED by Next on every dev/build run, and the committed
#    copy imported `./.next/dev/types/routes.d.ts` and
#    `./.next/dev/types/root-params.d.ts`, which only exist after a dev run.
#    A fresh clone therefore failed `tsc` and
#    libs/trading-core/tests/test_repo_reference_integrity.py. apps/web/.gitignore
#    now ignores it, and `npm run build:web` recreates it locally as intended.
#
# Usage: bash scripts/apply-batch04-deletes.sh
# Safe to run from the monorepo root or from whitelabel-copytrade/.
set -euo pipefail

# Resolve the monorepo root from this script's own location so the command works
# from any working directory and from inside the release package.
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "${SCRIPT_DIR}/.." && pwd)"
cd "${REPO_ROOT}"

if ! git rev-parse --show-toplevel >/dev/null 2>&1; then
  echo "apply-batch04-deletes: ${REPO_ROOT} is not inside a git work tree; nothing to do." >&2
  exit 0
fi

PROXY="apps/admin-web/src/proxy.ts"
MIDDLEWARE="apps/admin-web/src/middleware.ts"

# Deleting one request entrypoint is only safe when the survivor carries every behaviour the deleted
# module had. Each marker below is one of those behaviours, and the check runs BEFORE anything is
# removed: a proxy that lost the nonce, the CSP header, the static headers, the allowlist, the
# `?next=` destination or the matcher refuses the delete instead of shipping a silent regression.
# The behaviours themselves are proven one by one in src/tests/entrypoint-proxy.test.ts.
guard_proxy() {
  if [ ! -f "${PROXY}" ]; then
    echo "apply-batch04-deletes: ${PROXY} is absent - refusing to remove ${MIDDLEWARE}." >&2
    exit 1
  fi

  local missing=()
  # A plain substring of the survivor.
  need_fixed() {
    grep -qF -- "$1" "${PROXY}" || missing+=("$2 ($1)")
  }
  # An alternation: either spelling of the same behaviour is fine.
  need_any() {
    grep -qE -- "$1" "${PROXY}" || missing+=("$2 ($1)")
  }

  need_any   "export (function|const) proxy" "the entrypoint Next 16 calls"
  need_fixed "PUBLIC_PATHS"                 "the public-path allowlist"
  need_fixed "x-nonce"                      "the per-request CSP nonce forwarded to the render"
  need_fixed "Content-Security-Policy"      "the CSP header built from that nonce"
  need_fixed "X-Frame-Options"              "the static security headers"
  need_fixed "next="                        "the login redirect that keeps its destination"
  need_fixed "matcher"                      "the matcher that keeps static assets out"
  # The API exemption, spelled as a prefix test on the pathname.
  need_any   "startsWith\\('/api/'\\)|/api/\*" "the /api/* exemption"

  if [ "${#missing[@]}" -gt 0 ]; then
    echo "apply-batch04-deletes: ${PROXY} does not yet carry every behaviour of ${MIDDLEWARE}; refusing to delete it." >&2
    printf '  missing: %s\n' "${missing[@]}" >&2
    exit 1
  fi
}

FILES=(
  "${MIDDLEWARE}"
  "apps/web/next-env.d.ts"
)

# Nothing to guard once the entrypoint is gone: a second run must stay a no-op.
if [ -e "${MIDDLEWARE}" ] || git ls-files --error-unmatch -- "${MIDDLEWARE}" >/dev/null 2>&1; then
  guard_proxy
fi

for file in "${FILES[@]}"; do
  # Tracked? Then remove it from the index and the working tree.
  if git ls-files --error-unmatch -- "${file}" >/dev/null 2>&1; then
    git rm -q -- "${file}"
    echo "apply-batch04-deletes: removed tracked file ${file}"
    continue
  fi

  # Untracked but present (for example a leftover dev run): remove the file only.
  if [ -e "${file}" ]; then
    rm -f -- "${file}"
    echo "apply-batch04-deletes: removed untracked file ${file}"
    continue
  fi

  echo "apply-batch04-deletes: ${file} already absent; skipping"
done

echo "apply-batch04-deletes: done"
