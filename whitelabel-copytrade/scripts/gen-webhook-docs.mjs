// # NEW — Generates versioned webhook documentation directly from the API event catalog and schemas

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, '..');
const outputPath = resolve(repositoryRoot, 'docs/WEBHOOK_EVENTS.md');
const tsConfigPath = resolve(repositoryRoot, 'apps/api/tsconfig.json');
const require = createRequire(import.meta.url);

process.env.TS_NODE_PROJECT = tsConfigPath;
process.env.TS_NODE_TRANSPILE_ONLY = '1';
require('ts-node/register/transpile-only');

const { DEVELOPER_EVENT_TYPES } = require(resolve(
  repositoryRoot,
  'apps/api/src/modules/developer-platform/developer.types.ts',
));
const { DEVELOPER_EVENT_PAYLOAD_SCHEMAS } = require(resolve(
  repositoryRoot,
  'apps/api/src/modules/developer-platform/event-schemas/developer-event-schemas.ts',
));

const definitions = [...DEVELOPER_EVENT_TYPES].sort((left, right) => left.eventType.localeCompare(right.eventType));
const catalogEventTypes = definitions.map((definition) => definition.eventType);
const schemaEventTypes = Object.keys(DEVELOPER_EVENT_PAYLOAD_SCHEMAS).sort();
const missingSchemas = catalogEventTypes.filter((eventType) => !Object.hasOwn(DEVELOPER_EVENT_PAYLOAD_SCHEMAS, eventType));
const orphanSchemas = schemaEventTypes.filter((eventType) => !catalogEventTypes.includes(eventType));

if (missingSchemas.length > 0 || orphanSchemas.length > 0) {
  process.stderr.write(
    [
      ...(missingSchemas.length > 0 ? [`Catalog events without schemas: ${missingSchemas.join(', ')}`] : []),
      ...(orphanSchemas.length > 0 ? [`Schemas not present in catalog: ${orphanSchemas.join(', ')}`] : []),
    ].join('\n') + '\n',
  );
  process.exit(1);
}

const lines = [
  '<!-- GENERATED by scripts/gen-webhook-docs.mjs. Do not edit this file directly. -->',
  '',
  '# Developer webhook events',
  '',
  'Every webhook is an immutable projection of a tenant-scoped domain event. Event payloads use the versioned JSON Schemas listed below; money, prices, and quantities are decimal strings, never JSON floating-point numbers.',
  '',
  'Unknown event types, source mismatches, and payloads that fail their schema are not delivered. Subscribe only to event types returned by the authenticated `GET /developer/event-types` catalog.',
  '',
  `Catalog entries: ${definitions.length}. Schema entries: ${schemaEventTypes.length}.`,
  '',
  '| Event type | Version | Resource | Source | Schema ID |',
  '| --- | --- | --- | --- | --- |',
];

for (const definition of definitions) {
  const schema = DEVELOPER_EVENT_PAYLOAD_SCHEMAS[definition.eventType];
  lines.push(
    `| \`${definition.eventType}\` | ${definition.eventVersion} | \`${definition.resourceType}\` | \`${definition.source}\` | \`${schema.$id}\` |`,
  );
}

lines.push('', '## Versioned payload schemas', '');
for (const definition of definitions) {
  const schema = DEVELOPER_EVENT_PAYLOAD_SCHEMAS[definition.eventType];
  lines.push(
    `### ${definition.eventType} (${definition.eventVersion})`,
    '',
    schema.description,
    '',
    `Schema URI: \`${schema.$id}\`.`,
    '',
    '```json',
    JSON.stringify(schema, null, 2),
    '```',
    '',
  );
}

const generated = `${lines.join('\n')}\n`;
const checkOnly = process.argv.includes('--check');
if (checkOnly) {
  let current;
  try {
    current = await readFile(outputPath, 'utf8');
  } catch {
    process.stderr.write('docs/WEBHOOK_EVENTS.md is missing; run node scripts/gen-webhook-docs.mjs to create it.\n');
    process.exit(1);
  }
  if (current !== generated) {
    process.stderr.write('docs/WEBHOOK_EVENTS.md is stale; run node scripts/gen-webhook-docs.mjs and commit the result.\n');
    process.exit(1);
  }
  process.stdout.write(`Webhook documentation is current (${definitions.length} catalog entries, ${schemaEventTypes.length} schemas).\n`);
} else {
  await writeFile(outputPath, generated, 'utf8');
  process.stdout.write(`Wrote docs/WEBHOOK_EVENTS.md (${definitions.length} catalog entries, ${schemaEventTypes.length} schemas).\n`);
}
